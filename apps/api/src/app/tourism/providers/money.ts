/**
 * هر دو تأمین‌کننده (هتل‌یار و اقامت۲۴) قیمت را **ریال** می‌دهند و صنعت‌پی هم
 * از آبان ۱۴۰۵ همه‌جا — کیف پول، دیتابیس، تسویه — ریال کار می‌کند؛ پس در مرز
 * تأمین‌کننده تبدیل واحدی نیست. این تابع فقط عدد خام را به ریال صحیح
 * نرمال می‌کند (رشته/اعشار/خالی از پاسخ‌ها).
 */
export function providerRial(rial: number): number {
  const value = Math.round(Number(rial ?? 0));
  return Number.isFinite(value) ? value : 0;
}
