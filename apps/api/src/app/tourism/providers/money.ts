/**
 * هر دو تأمین‌کننده (هتل‌یار و اقامت۲۴) قیمت را **ریال** می‌دهند، ولی صنعت‌پی
 * همه‌جا — کیف پول، دیتابیس، تسویه — تومان کار می‌کند. تبدیل فقط در مرز هر
 * تأمین‌کننده (مپر/پرووایدر/webhook) انجام می‌شود تا هیچ عدد ریالی به سرویس و
 * دیتابیس نشت نکند.
 */
export function rialToToman(rial: number): number {
  return Math.round((rial ?? 0) / 10);
}
